#!/usr/bin/env python3
# /// script
# requires-python = ">=3.10"
# dependencies = ["pyyaml"]
# ///
"""Generate the README "What's in the corpus" stat rows from the live corpus.

Replaces the content between the `<!-- STATS:START ... -->` and `<!-- STATS:END -->`
markers in README.md so the headline counts can never drift from the data. Run in
CI by publish.yml on every merge, alongside the export rebuild.

Usage:
  uv run scripts/gen_readme_stats.py            # rewrite README.md in place
  uv run scripts/gen_readme_stats.py --check    # exit 1 if README is out of date
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
INCIDENTS = REPO / "incidents"
TAXONOMY = REPO / "schema" / "taxonomy.yaml"
README = REPO / "README.md"
START = "<!-- STATS:START — auto-generated by scripts/gen_readme_stats.py; do not edit by hand -->"
END = "<!-- STATS:END -->"


def compute_rows() -> str:
    records = [yaml.safe_load(p.read_text()) for p in sorted(INCIDENTS.glob("2*.yaml"))]
    total = len(records)
    incidents = sum(1 for r in records if r.get("incident_type") == "incident")
    hazards = sum(1 for r in records if r.get("incident_type") == "hazard")
    years = [int(str(r["date"])[:4]) for r in records if r.get("date")]
    span = f"{min(years)}–{max(years)}" if years else ""

    present = set()
    for r in records:
        present.add(r.get("primary_failure_class"))
        present.update(fc["class"] for fc in r.get("failure_classes", []))
    all_classes = {c["name"] for c in yaml.safe_load(TAXONOMY.read_text())["classes"]}
    covered = len(present & all_classes)

    cve = sum(1 for p in INCIDENTS.glob("2*.yaml") if "CVE-" in p.read_text())

    return (
        f"{START}\n"
        f"| **Incidents** | {total} and growing ({span}) — see the live count badge above |\n"
        f"| **Type** | {incidents} realized incidents · {hazards} demonstrated hazards / near-misses |\n"
        f"| **Coverage** | {covered} of {len(all_classes)} failure classes; {cve} CVE-backed |\n"
        f"{END}"
    )


def main() -> int:
    block = compute_rows()
    text = README.read_text()
    new = re.sub(re.escape(START) + r".*?" + re.escape(END), block, text, flags=re.DOTALL)
    if START not in text or END not in text:
        print("error: STATS markers not found in README.md", file=sys.stderr)
        return 2
    if "--check" in sys.argv:
        if new != text:
            print("README stats are out of date — run: uv run scripts/gen_readme_stats.py")
            return 1
        print("README stats up to date")
        return 0
    README.write_text(new)
    print("README stats regenerated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
